import {defineField, defineType} from 'sanity'

export const siteSettings = defineType({
  name: 'siteSettings',
  title: 'Configuración General del Sitio',
  type: 'document',
  groups: [
    {name: 'institucional', title: 'Institucional', default: true},
    {name: 'contacto', title: 'Contacto'},
    {name: 'redes', title: 'Redes sociales'},
  ],
  fields: [
    defineField({
      name: 'nombreInstitucional',
      title: 'Nombre institucional',
      type: 'string',
      group: 'institucional',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'logo',
      title: 'Logo',
      type: 'image',
      group: 'institucional',
      options: {hotspot: true},
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'telefono',
      title: 'Teléfono',
      description: 'Formato internacional para el link tel:, ej. +50212345678',
      type: 'string',
      group: 'contacto',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'email',
      title: 'Email general',
      type: 'string',
      group: 'contacto',
      validation: (Rule) => Rule.required().email(),
    }),
    defineField({
      name: 'direccion',
      title: 'Dirección',
      type: 'string',
      group: 'contacto',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'whatsapp',
      title: 'WhatsApp',
      description: 'Número en formato internacional sin signos, ej. 50212345678. Opcional — si está vacío, el botón de WhatsApp no se muestra.',
      type: 'string',
      group: 'contacto',
    }),
    defineField({
      name: 'mapsUrl',
      title: 'Link a Google Maps',
      description: 'URL a la que enlaza la dirección ("abre en Google Maps"). Opcional.',
      type: 'url',
      group: 'contacto',
      validation: (Rule) => Rule.uri({scheme: ['http', 'https']}),
    }),
    defineField({
      name: 'mapsEmbedUrl',
      title: 'URL de embed de Google Maps',
      description: 'URL del iframe para el mapa embebido en Contáctanos. Opcional.',
      type: 'url',
      group: 'contacto',
      validation: (Rule) => Rule.uri({scheme: ['http', 'https']}),
    }),
    defineField({
      name: 'facebookUrl',
      title: 'Link Facebook',
      type: 'url',
      group: 'redes',
      validation: (Rule) => Rule.uri({scheme: ['http', 'https']}),
    }),
    defineField({
      name: 'twitterUrl',
      title: 'Link Twitter/X',
      type: 'url',
      group: 'redes',
      validation: (Rule) => Rule.uri({scheme: ['http', 'https']}),
    }),
    defineField({
      name: 'youtubeUrl',
      title: 'Link YouTube',
      type: 'url',
      group: 'redes',
      validation: (Rule) => Rule.uri({scheme: ['http', 'https']}),
    }),
    defineField({
      name: 'instagramUrl',
      title: 'Link Instagram',
      type: 'url',
      group: 'redes',
      validation: (Rule) => Rule.uri({scheme: ['http', 'https']}),
    }),
  ],
  preview: {
    select: {title: 'nombreInstitucional', media: 'logo'},
  },
})
